import type { ReactNode } from "react";
import { AppShell } from "@/components/layout/app-shell";

/*
 * Оболочка продукта — шапка, подвал, провайдер живых обновлений — живёт
 * здесь, а не внутри каждой страницы.
 *
 * Раньше её рисовала каждая страница сама, и из-за этого при любом переходе,
 * где успевал показаться скелетон, навигация размонтировалась и появлялась
 * снова: замер во время живого клика давал число элементов навигации
 * 1 → 0 → 1. Скелетон — это запасной вариант Suspense, он подменяет только
 * содержимое сегмента; всё, что выше по дереву, обязано пережить переход, и
 * теперь оболочка именно там.
 *
 * Группа `(app)` не участвует в адресах: `(app)/catalog` — это по-прежнему
 * `/catalog`. Она нужна только чтобы отделить страницы с этой оболочкой от
 * страниц входа, у которых своя (`auth/layout.tsx`).
 */
export default function AppLayout({ children }: { children: ReactNode }) {
  return <AppShell>{children}</AppShell>;
}
